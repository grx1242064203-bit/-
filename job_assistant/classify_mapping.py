def normalize_industry(raw: str) -> str:
    """将飞书表的原始行业分类归一化为 18 类之一"""
    if not raw:
        return "其他"
    raw = raw.strip()
    # 精确匹配
    if raw in INDUSTRY_MAPPING:
        return INDUSTRY_MAPPING[raw]
    # 关键词兜底
    for norm, keywords in INDUSTRY_KEYWORDS:
        if any(kw in raw for kw in keywords):
            return norm
    return "其他"


def normalize_company_type(raw: str) -> str:
    """将飞书表的原始企业性质归一化为 5 类之一"""
    if not raw:
        return "其他"
    raw = raw.strip()
    if raw in COMPANY_TYPE_MAPPING:
        return COMPANY_TYPE_MAPPING[raw]
    # 关键词兜底
    if any(k in raw for k in ["国企", "央企", "银行"]):
        return "国央企"
    if "民企" in raw or "民营" in raw:
        return "民企"
    if any(k in raw for k in ["外企", "合资", "港澳台"]):
        return "外企"
    if any(k in raw for k in ["事业", "社会", "公益"]):
        return "事业单位"
    return "其他"


def normalize_industries(raw_list: List[str]) -> List[str]:
    """归一化行业列表(飞书记录可能有多个行业标签)"""
    result = []
    for raw in raw_list or []:
        norm = normalize_industry(raw)
        if norm and norm not in result:
            result.append(norm)
    return result if result else ["其他"]
